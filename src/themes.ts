export interface AppearanceTheme {
  id: string;
  name: string;
  description: string;
  mode: "light" | "dark";
  tokens: Record<string, string>;
}

type Palette = [
  background: string,
  surface: string,
  raised: string,
  text: string,
  muted: string,
  accent: string,
  secondary: string,
  success: string,
  warning: string,
  danger: string,
  border: string,
];

/** All visual choices live here; the stylesheet only consumes semantic tokens. */
function theme(
  id: string,
  name: string,
  description: string,
  mode: AppearanceTheme["mode"],
  palette: Palette,
  options: Record<string, string> = {},
): AppearanceTheme {
  const [
    bg,
    surface,
    raised,
    text,
    muted,
    accent,
    secondary,
    success,
    warning,
    danger,
    border,
  ] = palette;
  return {
    id,
    name,
    description,
    mode,
    tokens: {
      "--llm-theme-scheme": mode,
      "--llm-theme-bg": bg,
      "--llm-theme-surface": surface,
      "--llm-theme-raised": raised,
      "--llm-theme-text": text,
      "--llm-theme-muted": muted,
      "--llm-theme-accent": accent,
      "--llm-theme-accent-text": mode === "dark" ? bg : "#ffffff",
      "--llm-theme-secondary": secondary,
      "--llm-theme-success": success,
      "--llm-theme-warning": warning,
      "--llm-theme-danger": danger,
      "--llm-theme-border": border,
      "--llm-theme-radius": "14px",
      "--llm-theme-control-radius": "8px",
      "--llm-theme-shadow":
        mode === "dark"
          ? "0 8px 28px rgba(0, 0, 0, .24)"
          : "0 6px 24px rgba(30, 45, 65, .08)",
      "--llm-theme-background": bg,
      "--llm-theme-code": mode === "dark" ? bg : raised,
      "--llm-theme-font":
        '"Segoe UI", -apple-system, BlinkMacSystemFont, sans-serif',
      "--llm-theme-user-bg":
        "color-mix(in srgb, var(--llm-theme-accent) 17%, var(--llm-theme-surface))",
      ...options,
    },
  };
}

